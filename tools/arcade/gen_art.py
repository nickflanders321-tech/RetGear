"""Art lookup for the cards -> ArcadeArt.lua.

  python3 tools/arcade/gen_art.py <classic.sql> <addon dir>

NPC cards: name -> creature display id (the card shows that creature's own 3D model from the player's game files).
Place cards: name -> map folder of its zone (the card shows a piece of that zone's own world-map art).
"""
import re, sys, os
sql_path, addon = sys.argv[1:3]
src = open(os.path.join(os.path.dirname(__file__), 'gen.py'), encoding='utf-8').read()
head = src[:src.index("BAD = re.compile")]
sys.argv = ['gen.py', sql_path, '/tmp/qdb', addon]
ns = {}
exec(head, ns)
rows = ns['rows']
def clean(n): return re.sub(r'\s+', ' ', n).strip()
disp = {}
for e, n, m in rows('creature_template', ['Entry', 'Name', 'ModelId1']):
    n = clean(n); m = int(m or 0)
    if m and n.lower() not in disp: disp[n.lower()] = m
ZONE = {"Dun Morogh": "DunMorogh", "Badlands": "Badlands", "Blasted Lands": "BlastedLands", "Swamp of Sorrows": "SwampOfSorrows", "Duskwood": "Duskwood",
  "Wetlands": "Wetlands", "Elwynn Forest": "Elwynn", "Durotar": "Durotar", "Dustwallow Marsh": "Dustwallow", "Azshara": "Aszhara", "The Barrens": "Barrens",
  "Western Plaguelands": "WesternPlaguelands", "Stranglethorn Vale": "Stranglethorn", "Alterac Mountains": "Alterac", "Alterac Valley": "Alterac",
  "Loch Modan": "LochModan", "Westfall": "Westfall", "Deadwind Pass": "DeadwindPass", "Redridge Mountains": "Redridge", "Arathi Highlands": "Arathi",
  "Arathi Basin": "Arathi", "Burning Steppes": "BurningSteppes", "The Hinterlands": "Hinterlands", "Searing Gorge": "SearingGorge", "Tirisfal Glades": "Tirisfal",
  "Silverpine Forest": "Silverpine", "Eastern Plaguelands": "EasternPlaguelands", "Teldrassil": "Teldrassil", "Darkshore": "Darkshore", "Mulgore": "Mulgore",
  "Hillsbrad Foothills": "Hilsbrad", "Ashenvale": "Ashenvale", "Feralas": "Feralas", "Felwood": "Felwood", "Thousand Needles": "ThousandNeedles",
  "Desolace": "Desolace", "Stonetalon Mountains": "StonetalonMountains", "Tanaris": "Tanaris", "Un'Goro Crater": "UngoroCrater", "Moonglade": "Moonglade",
  "Winterspring": "Winterspring", "Silithus": "Silithus", "Undercity": "Undercity", "Stormwind City": "Stormwind", "Ironforge": "Ironforge",
  "Orgrimmar": "Orgrimmar", "Thunder Bluff": "ThunderBluff", "Darnassus": "Darnassis"}
cards = re.findall(r'^\s*\{ (\d), "((?:[^"\\]|\\.)*)", \d, \d+, "((?:[^"\\]|\\.)*)" \},', open(os.path.join(addon, 'ArcadeCards.lua'), encoding='utf-8').read(), re.M)
npc, zone, miss = {}, {}, 0
for kind, name, text in cards:
    name = name.replace('\\"', '"')
    if kind == '2':
        d = disp.get(name.lower())
        if d: npc[name] = d
        else: miss += 1
    elif kind == '3':
        z = name if text == 'Zone' else text.replace('Found in ', '')
        if z in ZONE: zone[name] = ZONE[z]
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
out = ["-- GENERATED by tools/arcade/gen_art.py: do not edit by hand.", "local _, RG = ...",
       "-- NPC card name -> creature display id (its model is shown from the player's own game files)", "RG.ARCADE_NPC = {"]
out += ["  [%s] = %d," % (q(k), v) for k, v in sorted(npc.items())]
out += ["}", "-- place card name -> folder of its zone's world map art", "RG.ARCADE_ZONE = {"]
out += ["  [%s] = %s," % (q(k), q(v)) for k, v in sorted(zone.items())]
out.append("}")
open(os.path.join(addon, "ArcadeArt.lua"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(npc), "npcs;", miss, "without display;", len(zone), "places")
