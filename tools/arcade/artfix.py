"""Card art the game can't find by itself -> ArcadeArtFix.lua.

  python3 tools/arcade/artfix.py <classic.sql> <wago dir> <addon dir>

From the game client's own tables (the data/wago export):
  - item icons: an item whose icon only lives on its appearance (WoW Forever's own items) gets that icon's file; an item
    this client doesn't have at all gets the icon of a client item of the same kind (a polearm's for a polearm)
  - dungeon and raid place cards: the dungeon's own loading screen, from the player's game files
"""
import csv, gzip, os, re, sys

sql_path, wago, addon = sys.argv[1:4]
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, 'gen.py'), encoding='utf-8').read()
head = src[:src.index("cards, seen = [], set()")]
saved = sys.argv; sys.argv = ['gen.py', sql_path, '/tmp/', addon]
ns = {}; exec(head, ns); sys.argv = saved
rows = ns['rows']

def tab(n):
    p = os.path.join(wago, n + ".csv.gz")
    return list(csv.DictReader(gzip.open(p, "rt", encoding="utf-8"))) if os.path.exists(p) else []
items = {int(r["ID"]): r for r in tab("Item")}
sparse_q = {int(r["ID"]): int(r["OverallQualityID"] or 0) for r in tab("ItemSparse")}
appear = {r["ID"]: r for r in tab("ItemAppearance")}
ima = {}
for r in tab("ItemModifiedAppearance"):
    a = appear.get(r["ItemAppearanceID"])
    if a and a["DefaultIconFileDataID"] not in ("0", ""): ima.setdefault(int(r["ItemID"]), int(a["DefaultIconFileDataID"]))
classic = {}
for e, c, s, inv in rows('item_template', ['entry', 'class', 'subclass', 'InventoryType']):
    classic[int(e)] = (int(c), int(s), int(inv))
# the best client icon for each kind of item (class, subclass, slot), for items the client doesn't have
kind_icon = {}
for i, r in items.items():
    ic = int(r["IconFileDataID"] or 0) or ima.get(i, 0)
    if not ic: continue
    k = (int(r["ClassID"] or 0), int(r["SubclassID"] or 0), int(r["InventoryType"] or 0))
    q = sparse_q.get(i, 0)
    if k not in kind_icon or q > kind_icon[k][0]: kind_icon[k] = (q, ic)

# every card, as the add-on lists them
cards = []
for f in ("ArcadeCards.lua", "ArcadeDungeons.lua", "ArcadeField.lua", "ArcadeRaids.lua", "ArcadeHolidays.lua"):
    p = os.path.join(addon, f)
    if os.path.exists(p):
        for kind, name, ref in re.findall(r'^\s*\{ (\d), "((?:[^"\\]|\\.)*)", \d, (-?\d+), "(?:[^"\\]|\\.)*" \},', open(p, encoding="utf-8").read(), re.M):
            cards.append((int(kind), name.replace('\\"', '"'), int(ref)))

icons, guessed = {}, []
for kind, name, ref in cards:
    if kind != 1 or ref <= 0: continue
    r = items.get(ref)
    if r and int(r["IconFileDataID"] or 0): continue
    if ref in ima: icons[ref] = ima[ref]; continue
    k = classic.get(ref)
    if k and k in kind_icon: icons[ref] = kind_icon[k][1]; guessed.append(name)
    elif k:
        near = [v for kk, v in kind_icon.items() if kk[0] == k[0] and kk[1] == k[1]]
        if near: icons[ref] = max(near)[1]; guessed.append(name)

# loading screens for the dungeon and raid place cards (a screen several maps share isn't any one place's)
ALIAS = {"Stormwind Stockade": "The Stockade", "Deadmines": "The Deadmines", "Sunken Temple": "The Temple of Atal'Hakkar",
         "Barrow Deeps": "The Barrow Deeps", "The Hyjal Summit": "Hyjal Summit"}
screens = {r["ID"]: r for r in tab("LoadingScreens")}
use = {}
maps = [r for r in tab("Map") if r["InstanceType"] in ("1", "2")]
for r in maps: use[r["LoadingScreenID"]] = use.get(r["LoadingScreenID"], 0) + 1
place_names = {name for kind, name, ref in cards if kind == 3}
places = {}
for r in maps:
    s = screens.get(r["LoadingScreenID"])
    if not s or use[r["LoadingScreenID"]] > 1: continue
    name = ALIAS.get(r["MapName_lang"], r["MapName_lang"])
    if name not in place_names: continue
    main, narrow = int(s["MainImageFileDataID"] or 0), int(s["NarrowScreenFileDataID"] or 0)
    if main: places[name] = (main, 1)        # (a wide picture)
    elif narrow: places[name] = (narrow, 0)  # (a 4:3 picture)

L = ["-- GENERATED by tools/arcade/artfix.py: do not edit by hand.",
     "-- Card art the game can't find by itself, from the game client's own tables:",
     "--   RG.ARCADE_ITEM_ICON: item id -> icon file (an icon only on the item's appearance, or a like item's for one this",
     "--   client doesn't have); RG.ARCADE_PLACE_FILE: dungeon or raid -> { its loading screen's file, 1 if wide }",
     "local _, RG = ...",
     "RG.ARCADE_ITEM_ICON = {"]
for i in sorted(icons): L.append("  [%d] = %d," % (i, icons[i]))
L.append("}")
L.append("RG.ARCADE_PLACE_FILE = {")
for n in sorted(places): L.append('  ["%s"] = { %d, %d },' % (n.replace('"', '\\"'), places[n][0], places[n][1]))
L.append("}")
open(os.path.join(addon, "ArcadeArtFix.lua"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("art fixes: %d item icons (%d from a like item: %s), %d place screens" % (len(icons), len(guessed), ", ".join(guessed[:5]), len(places)), file=sys.stderr)
