"""Class cards for the Arena -> ArcadeClasses.lua.

  python3 tools/arcade/classes.py <classic.sql> <addon dir>

An Arena item card is a class card when the item itself can only be used by one class (item_template.AllowableClass
names a single class): the tier-set pieces. Battle.lua gives each one a design from that class's list.
"""
import re, sys, json
sql_path, addon = sys.argv[1:3]
src = open(addon + '/tools/arcade/gen.py').read()
sys.argv = ['gen.py', sql_path, '/nonexistent/', addon]
exec(src.split("cards, seen = [], set()")[0].split("sql_path, qdb, addon = sys.argv[1:4]")[1].replace("if not qdb.endswith('/'): qdb += '/'", ""), globals())
BITS = {1: 'WARRIOR', 2: 'PALADIN', 4: 'HUNTER', 8: 'ROGUE', 16: 'PRIEST', 64: 'SHAMAN', 128: 'MAGE', 256: 'WARLOCK', 1024: 'DRUID'}
info = {int(a): int(b) & 1535 for a, b in rows('item_template', ['entry', 'AllowableClass'])}
data = open(addon + '/ArcadeCards.lua', encoding='utf-8').read()
out = {}
for name, ref in re.findall(r'\{ 1, "((?:[^"\\]|\\.)*)", \d, (\d+),', data):
    c = BITS.get(info.get(int(ref), 0))
    if c: out[name] = c
lines = ['-- GENERATED by tools/arcade/classes.py: do not edit by hand.',
         '-- Class cards: tier-set pieces only that class can wear (from the item data) are class cards in the Arena.',
         'local _, RG = ...', 'RG.ARCADE_CLASS = {']
for n in sorted(out): lines.append('  [%s] = "%s",' % (json.dumps(n), out[n]))
lines.append('}')
open(addon + '/ArcadeClasses.lua', 'w').write('\n'.join(lines) + '\n')
print(len(out), 'class cards')
