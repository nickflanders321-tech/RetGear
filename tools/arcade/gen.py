"""Card list for the hidden arcade -> ArcadeCards.lua.

  python3 tools/arcade/gen.py <classic.sql> <qdb dir> <addon dir>

Items (epic and legendary), NPCs (bosses and rare elites) and places (zones and subzones),
all from the cMaNGOS classic DB and QuestieDB's Forever zone tables. Each card is
{ kind (1 item, 2 npc, 3 place), name, tier (1 common .. 5 legendary subject), ref, text }.
"""
import re, sys, os, random
sql_path, qdb, addon = sys.argv[1:4]
if not qdb.endswith('/'): qdb += '/'
sql = open(sql_path, encoding='utf-8', errors='replace').read()
def columns(t):
    m = re.search(r"CREATE TABLE `%s` \((.*?)\) ENGINE" % t, sql, re.S)
    return re.findall(r"^\s*`(\w+)`", m.group(1), re.M)
def rows(t, want):
    cols = columns(t); idx = [cols.index(w) for w in want]; out = []
    for m in re.finditer(r"INSERT INTO `%s` VALUES " % t, sql):
        i, n = m.end(), len(sql)
        while i < n and sql[i] == '(':
            i += 1; row = []; cur = []; inq = False
            while True:
                c = sql[i]
                if inq:
                    if c == '\\': cur.append(sql[i + 1]); i += 2; continue
                    if c == "'":
                        if sql[i + 1] == "'": cur.append("'"); i += 2; continue
                        inq = False; i += 1; continue
                    cur.append(c); i += 1; continue
                if c == "'": inq = True; i += 1; continue
                if c == ',': row.append(''.join(cur)); cur = []; i += 1; continue
                if c == ')': row.append(''.join(cur)); i += 1; break
                cur.append(c); i += 1
            out.append([row[j] for j in idx])
            if sql[i] == ',': i += 1
            else: break
    return out
BAD = re.compile(r"\b(test|deprecated|old|unused|dnd|ph|npc|template|\[|\(|qa|monster|zzold|obsolete|placeholder|copy)\b|^\s*$", re.I)
def clean(n): return re.sub(r"\s+", " ", n).strip()
def ok(n): return n and not BAD.search(n) and not n.startswith(("[", "*")) and len(n) < 40

cards, seen = [], set()
def add(kind, name, tier, ref, text):
    k = name.lower()
    if k in seen: return
    seen.add(k); cards.append((kind, name, tier, ref, text))

# items: legendary and epic, highest first
it = [(clean(r[1]), int(r[0]), int(r[2]), int(r[3]), int(r[4])) for r in rows('item_template', ['entry', 'name', 'Quality', 'ItemLevel', 'RequiredLevel'])]
JUNK = re.compile(r"^\d+ |Epic (Warrior|Mage|Rogue|Priest|Paladin|Hunter|Druid|Shaman|Warlock)|Pwnage|Audacity|Martin|^Stone of |Brownell|Backus|Goodman|Tester|Gamemaster|\bGM\b|'s (Ring|Sword|Blade|Staff)\b", re.I)
it = [x for x in it if x[2] >= 4 and x[3] >= 40 and ok(x[0]) and not JUNK.search(x[0])]
it.sort(key=lambda x: (-x[2], -x[3], x[0]))
n = 0
for name, eid, q, il, rl in it:
    if n >= 430: break
    if name.lower() in seen: continue
    add(1, name, 5 if q >= 5 else (4 if il >= 70 else 3), eid, ("Legendary" if q >= 5 else "Epic") + " item, item level %d" % il)
    n += 1

# NPCs: world bosses first, then rare elites and rares
TYPE = {1: "beast", 2: "dragonkin", 3: "demon", 4: "elemental", 5: "giant", 6: "undead", 7: "humanoid", 8: "critter", 9: "mechanical"}
RANK = {2: "Rare elite", 3: "Boss", 4: "Rare"}
cr = [(clean(r[1]), int(r[0]), int(r[4]), int(r[5]), int(r[6] or 0)) for r in rows('creature_template', ['Entry', 'Name', 'SubName', 'MinLevel', 'MaxLevel', 'Rank', 'CreatureType'])]
cr = [x for x in cr if x[3] in (2, 3, 4) and x[2] >= 8 and ok(x[0])]
cr.sort(key=lambda x: (-(x[3] == 3), -x[2], x[0]))
n = 0
for name, eid, lvl, rank, ct in cr:
    if n >= 400: break
    if name.lower() in seen: continue
    tier = 5 if (rank == 3 and lvl >= 58) else (4 if rank == 3 else (3 if rank == 2 else 2))
    add(2, name, tier, ct, "%s, level %d %s" % (RANK[rank], lvl, TYPE.get(ct, "creature")))
    n += 1

# places: zones, then subzones named in QuestieDB's Forever zone table
zs = open(qdb + 'support/Forever/Zones/areaIdToUiMapId.lua', encoding='utf-8').read()
src = open(os.path.join(os.path.dirname(__file__), '..', 'fishloot', 'gen.py'), encoding='utf-8').read()
a = src.index("AREA = {"); b = src.index("for m in re.finditer", a)
ns = {}; exec(src[a:b], ns)
for z in ns['AREA'].values(): add(3, z, 3, 0, "Zone")
GENERIC = {"ruins", "camp", "the", "cave", "caves", "tower", "mine", "village", "outpost", "keep", "temple"}
subs = re.findall(r"--\s*([^>\n]+?)\s*->\s*([^\n]+?)\s*$", zs, re.M)
random.seed(7)
random.shuffle(subs)
n = 0
for s, parent in subs:
    s, parent = clean(s), clean(parent)
    if s.lower() in GENERIC or len(s) < 4 or not ok(s) or n >= 330: continue
    if s.lower() in seen: continue
    add(3, s, 1 if n % 3 else 2, 0, "Found in " + parent)
    n += 1

out = ["-- GENERATED by tools/arcade/gen.py: do not edit by hand.",
       "-- The hidden card game's cards: { kind (1 item, 2 NPC, 3 place), name, subject tier 1-5, item id / creature type, text }",
       "local _, RG = ...", "RG.ARCADE_DATA = {"]
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
for kind, name, tier, ref, text in cards:
    out.append("  { %d, %s, %d, %d, %s }," % (kind, q(name), tier, ref, q(text)))
out.append("}")
open(os.path.join(addon, "ArcadeCards.lua"), "w", encoding="utf-8").write("\n".join(out) + "\n")
import collections
print(len(cards), collections.Counter(c[0] for c in cards), collections.Counter(c[2] for c in cards))
