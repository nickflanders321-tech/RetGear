#!/usr/bin/env python3
"""How close the camera sits on each NPC card's model, from the model's own proportions in WoW Forever's game data.

A card frames an upright creature head and chest (RG.ArcadeModelZoom: by creature type). That suits a slim, upright
model (a human, an elf), but a hunched or stocky one (a quilboar, an ogre, a gnome) with the same zoom fills the card
with its head. The game's model table (CreatureModelData) gives each model's bounding box: its height over its length
is how upright it is. This writes that number for every NPC card (ArcadeFrame.lua: RG.ARCADE_SHAPE), and the add-on
zooms in less the less upright the model is.

Usage: python3 tools/arcade/frame.py <wago dir> <addon dir>
"""
import csv, gzip, os, re, sys
W, ROOT = sys.argv[1], sys.argv[2]
def table(n): return csv.DictReader(gzip.open(os.path.join(W, n + ".csv.gz"), "rt", encoding="utf-8"))
model = {r["ID"]: r for r in table("CreatureModelData")}
disp = {r["ID"]: r for r in table("CreatureDisplayInfo")}
creature = {r["ID"]: r for r in table("Creature")}

def lua_map(src, name):
    """["Card name"] = number entries of RG.<name> = { ... }"""
    m = re.search(r"^RG\.%s = \{\n(.*?)^\}" % re.escape(name), src, re.S | re.M)
    out = {}
    if m:
        for k, v in re.findall(r'^\s*\["((?:[^"\\]|\\.)*)"\]\s*=\s*(-?\d+)', m.group(1), re.M):
            out[k.replace('\\"', '"').replace("\\\\", "\\")] = int(v)
    return out

DISP = [("ArcadeArt.lua", "ARCADE_NPC"), ("ArcadeDungeons.lua", "ARCADE_DUNGEON_NPC"), ("ArcadeField.lua", "ARCADE_FIELD_DISPLAY"),
        ("ArcadeRaids.lua", "ARCADE_RAID_NPC"), ("ArcadeHolidays.lua", "ARCADE_HOLIDAY_NPC")]
CRE = [("ArcadeDungeons.lua", "ARCADE_DUNGEON_CREATURE"), ("ArcadeField.lua", "ARCADE_FIELD_CREATURE"),
       ("ArcadeRaids.lua", "ARCADE_RAID_CREATURE"), ("ArcadeHolidays.lua", "ARCADE_HOLIDAY_CREATURE")]
src = {}
def read(f):
    if f not in src: src[f] = open(os.path.join(ROOT, f), encoding="utf-8").read()
    return src[f]
names = {}
for f, t in CRE:
    for k, cid in lua_map(read(f), t).items():
        d = (creature.get(str(cid)) or {}).get("DisplayID_0")
        if d and d != "0": names[k] = int(d)
for f, t in DISP:
    for k, d in lua_map(read(f), t).items():
        if d > 0: names[k] = d

def upright(d):
    c = disp.get(str(d)); m = c and model.get(c["ModelID"])
    if not m: return None
    g = [float(m["GeoBox_%d" % i]) for i in range(6)]
    length, width, height = g[3] - g[0], g[4] - g[1], g[5] - g[2]
    if height <= 0 or max(length, width) <= 0: return None
    return round(height / max(length, width), 2)

shape = {k: upright(d) for k, d in names.items()}
shape = {k: v for k, v in shape.items() if v is not None}
def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
with open(os.path.join(ROOT, "ArcadeFrame.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("local _, RG = ...\n")
    f.write("-- How upright each NPC card's model is: its height over its length, from WoW Forever's model table\n"
            "-- (CreatureModelData). The card zooms in less on a hunched or stocky model (RG.ArcadeModelZoom).\n"
            "-- Generated by tools/arcade/frame.py: don't edit by hand.\n")
    f.write("RG.ARCADE_SHAPE = {\n")
    for k in sorted(shape): f.write("  [%s] = %s,\n" % (q(k), shape[k]))
    f.write("}\n")
print("card framing: %d of %d NPC models measured" % (len(shape), len(names)))
