"""Each class's three raid sets for the raider cards' 3D models -> ArcadeGearSets.lua.

  python3 tools/arcade/raidsets.py <classic.sql> <addon dir>

Tier 1, 2 and 3 (Might, Wrath, Dreadnaught...): the eight armour pieces of each, from the original game's items (a set's
pieces are named "<Set> Helm" or "Helm of <Set>"). A raider card wears one of its class's three, chosen by the raider's
name, so two raiders of the same race and class don't look the same (Arcade.lua: dressModel; the card says which).
"""
import re, sys, os
sql_path, addon = sys.argv[1:3]
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'gen.py'), encoding='utf-8').read().split("BAD = re.compile")[0].replace("sql_path, qdb, addon = sys.argv[1:4]\nif not qdb.endswith('/'): qdb += '/'\n", ""))
SETS = {"WARRIOR": ("Might", "Wrath", "Dreadnaught"), "PALADIN": ("Lawbringer", "Judgement", "Redemption"),
        "HUNTER": ("Giantstalker", "Dragonstalker", "Cryptstalker"), "ROGUE": ("Nightslayer", "Bloodfang", "Bonescythe"),
        "PRIEST": ("Prophecy", "Transcendence", "Faith"), "SHAMAN": ("Earthfury", "Ten Storms", "Earthshatter"),
        "MAGE": ("Arcanist", "Netherwind", "Frostfire"), "WARLOCK": ("Felheart", "Nemesis", "Plagueheart"),
        "DRUID": ("Cenarion", "Stormrage", "Dreamwalker")}
SLOTS = {1: "head", 3: "shoulder", 5: "chest", 20: "chest", 6: "waist", 7: "legs", 8: "feet", 9: "wrist", 10: "hands"}
ORDER = ("head", "shoulder", "chest", "waist", "legs", "feet", "wrist", "hands")
items = list(rows('item_template', ['entry', 'name', 'Quality', 'InventoryType', 'itemset']))
out = ["-- GENERATED by tools/arcade/raidsets.py: do not edit by hand.", "local _, RG = ...",
       "-- each class's raid sets (tier 1, 2, 3): { name, { item ids: head, shoulders, chest, waist, legs, feet, wrists, hands } }",
       "RG.ARCADE_GEAR_SETS = {"]
for cls in sorted(SETS):
    sets = []
    for w in SETS[cls]:
        got = {}
        for eid, name, q, inv, iset in items:
            if int(q) != 4 or int(inv) not in SLOTS or not int(iset or 0): continue
            if re.search(r"^%s\b|\bof (the )?%s$" % (re.escape(w), re.escape(w)), name):
                s = SLOTS[int(inv)]
                if s not in got or int(eid) < got[s][0]: got[s] = (int(eid), name)
        if len(got) != 8: raise SystemExit("%s %s: %d pieces" % (cls, w, len(got)))
        sets.append('{ "%s", { %s } }' % (w, ", ".join(str(got[s][0]) for s in ORDER)))
    out.append("  %s = { %s }," % (cls, ", ".join(sets)))
out.append("}")
open(os.path.join(addon, "ArcadeGearSets.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
print("\n".join(out))
