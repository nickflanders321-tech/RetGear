"""Raid gear per class for the hidden card game's 3D models -> ArcadeGear.lua.

  python3 tools/arcade/gear.py <classic.sql> <addon dir>

For each class and armour slot: the highest-level epic of that class's armour type, preferring
class-restricted pieces (the tier sets). Used to dress a model, so it only has to look like raid gear.
"""
import re, sys, os
sql_path, addon = sys.argv[1:3]
exec(open(os.path.join(os.path.dirname(__file__), 'gen.py'), encoding='utf-8').read().split("BAD = re.compile")[0].replace("sql_path, qdb, addon = sys.argv[1:4]\nif not qdb.endswith('/'): qdb += '/'\n", ""))
CLASSES = {"WARRIOR": (1, 4), "PALADIN": (2, 4), "HUNTER": (4, 3), "ROGUE": (8, 2), "PRIEST": (16, 1), "SHAMAN": (64, 3), "MAGE": (128, 1), "WARLOCK": (256, 1), "DRUID": (1024, 2)}
SLOTS = {1: "head", 3: "shoulder", 5: "chest", 20: "chest", 6: "waist", 7: "legs", 8: "feet", 9: "wrist", 10: "hands"}
it = rows('item_template', ['entry', 'name', 'Quality', 'ItemLevel', 'InventoryType', 'class', 'subclass', 'AllowableClass'])
JUNK = re.compile(r"^\d+ |Epic |Test|Pwnage|Brownell|Backus|Goodman|Martin|Qiraji|Zul|Hakkari|Band of", re.I)
out = ["-- GENERATED by tools/arcade/gen.py: do not edit by hand.", "-- Raid armour per class, used to dress the 3D models on the hidden card game's raider cards.", "local _, RG = ...", "RG.ARCADE_GEAR = {"]
for cls, (bit, armor) in CLASSES.items():
    best = {}
    for eid, name, q, il, inv, c, sc, allow in it:
        q, il, inv, c, sc, allow = int(q), int(il), int(inv), int(c), int(sc), int(allow)
        if q != 4 or c != 4 or inv not in SLOTS or il < 60 or il > 92 or JUNK.search(name): continue
        restricted = allow > 0 and allow != 32767 and (allow & bit) == bit and allow != 262143 and bin(allow).count("1") < 4
        if not restricted and not (sc == armor and allow in (-1, 0, 32767, 262143)): continue
        if restricted and sc != armor: continue
        slot = SLOTS[inv]
        score = (1 if restricted else 0, il)
        if slot not in best or score > best[slot][0]: best[slot] = (score, int(eid), name)
    ids = [best[s][1] for s in ("head", "shoulder", "chest", "waist", "legs", "feet", "wrist", "hands") if s in best]
    out.append("  %s = { %s }, -- %s" % (cls, ", ".join(map(str, ids)), "; ".join(best[s][2] for s in best)))
out.append("}")
open(os.path.join(addon, "ArcadeGear.lua"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out[4:-1]))
