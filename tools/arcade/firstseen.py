"""First Edition: when each WoW Forever original card arrived -> tools/arcade/firstseen.json and ArcadeFirst.lua.

  python3 tools/arcade/firstseen.py <addon dir>

WoW Forever's own content: the cards of its dungeons and raids, and its own rares (creature numbers above 240000).
Each card's first day is kept in firstseen.json (committed), so a card keeps its day across rebuilds; a card the data
gains later is stamped with the day of that rebuild. A raid's cards start on its opening day. Cards pulled in the
first four weeks after their day are First Edition prints (ArcadeFirstEdition.lua).
"""
import datetime, json, os, re, sys

addon = sys.argv[1]
here = os.path.dirname(os.path.abspath(__file__))
store = os.path.join(here, "firstseen.json")
seen = json.load(open(store)) if os.path.exists(store) else {}
today = datetime.date.today().isoformat()

def read(f):
    p = os.path.join(addon, f)
    return open(p, encoding="utf-8").read() if os.path.exists(p) else ""
def names(s): return [n.replace('\\"', '"') for n in re.findall(r'"((?:[^"\\]|\\.)*)"', s)]

found = {}   # card -> earliest day it can be had
# WoW Forever's dungeons (dungeons.py's NEW_DUNS)
NEW_DUNS = eval(re.search(r'NEW_DUNS = (\[.*?\])', open(os.path.join(here, "dungeons.py"), encoding="utf-8").read(), re.S).group(1))
for m in re.finditer(r'^  \{ "((?:[^"\\]|\\.)*)", \d+, \d+, \d+, \{ (.*) \} \},$', read("ArcadeDungeons.lua"), re.M):
    if m.group(1) in NEW_DUNS:
        for n in names(m.group(2)): found.setdefault(n, today)
# WoW Forever's raids (not Onyxia's Lair): from their opening day
for m in re.finditer(r'^  \{ "((?:[^"\\]|\\.)*)", (\d+), \d+, \d+, \{ (.*?) \}, raid = \{ size = \d+, opens = "([\d-]+)"', read("ArcadeRaids.lua"), re.M):
    if m.group(1) != "Onyxia's Lair":
        for n in names(m.group(3)): found[n] = max(found.get(n, today), m.group(4))
# WoW Forever's own rares
for m in re.finditer(r'^  \[(\d+)\] = \{ "((?:[^"\\]|\\.)*)", "[^"]*", \d+, [\d.]+, [\d.]+, "r" \},$', read("ArcadeField.lua"), re.M):
    if int(m.group(1)) > 240000: found.setdefault(m.group(2).replace('\\"', '"'), today)

added = 0
for n, d in found.items():
    if n not in seen: seen[n] = d; added += 1
    elif d > seen[n] and d > today: seen[n] = d   # (a raid's opening day moved later)
json.dump(dict(sorted(seen.items())), open(store, "w"), indent=0, ensure_ascii=False)

def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
L = ["-- GENERATED by tools/arcade/firstseen.py: do not edit by hand.",
     "-- First Edition: the day each WoW Forever original card arrived (its dungeon, raid or rare). Cards pulled in the four",
     "-- weeks after it are First Edition prints; until someone in your guild finds one, its Album slot shows \"???\".",
     "local _, RG = ...",
     "RG.ARCADE_FIRST = {"]
for n in sorted(seen):
    if n in found: L.append("  [%s] = %s," % (q(n), q(seen[n])))
L.append("}")
open(os.path.join(addon, "ArcadeFirst.lua"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("first edition: %d cards (%d new today)" % (len(found), added), file=sys.stderr)
