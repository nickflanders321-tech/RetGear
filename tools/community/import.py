"""Build CommunityQuests.lua from players' /wp share reports: quests WoW Forever's published data doesn't have yet
(new content, like Riverglades at launch), with where their givers and hand-ins stand.

Reports come from GitHub issues labelled "quests" (the "Share quests you found" form) and from any text files in
tools/community/reports/ (paste a report there by hand). A position is used when it was reported at least once; when
several players report one quest, the most common spot (to the nearest map unit) wins and the count is kept, so one
odd report can't move a quest that others agree on. Quests that QuestieDB's data has since learnt are dropped.

Usage: python3 tools/community/import.py [repo] [Objectives.lua]   (reads issues with `gh`; works without it too)
"""
import collections, json, os, re, subprocess, sys

REPO = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('GITHUB_REPOSITORY', 'nickflanders321-tech/RetGear')
OBJ = sys.argv[2] if len(sys.argv) > 2 else 'Objectives.lua'
HERE = os.path.dirname(os.path.abspath(__file__))

texts = []
try:
    raw = subprocess.run(['gh', 'api', '--paginate', 'repos/%s/issues?state=all&labels=quests&per_page=100' % REPO],
                         capture_output=True, text=True, check=True, timeout=60).stdout
    for chunk in re.findall(r'\[.*?\](?=\[|\s*$)', raw, re.S) or [raw]:
        try:
            for it in json.loads(chunk): texts.append(it.get('body') or '')
        except ValueError: pass
except Exception as e:
    print('note: could not read issues (%s); using local reports only' % e, file=sys.stderr)
rdir = os.path.join(HERE, 'reports')
if os.path.isdir(rdir):
    for fn in sorted(os.listdir(rdir)):
        if fn.endswith('.txt'): texts.append(open(os.path.join(rdir, fn), encoding='utf-8').read())

# only quests the published data doesn't have at all: a quest it knows but without a giver starts from an item or object,
# and a player's "giver" spot for it would only be where they happened to stand
known = {int(m.group(1)) for m in re.finditer(r'^\[(\d+)\]=\{', open(OBJ, encoding='utf-8').read(), re.M)}
known_s = known_e = known

def spot(field):
    p = field.split(',', 3)
    if len(p) < 3: return None
    try: m, x, y = int(p[0]), float(p[1]), float(p[2])
    except ValueError: return None
    if not (0 < m < 100000 and 0 <= x <= 100 and 0 <= y <= 100): return None
    return (m, round(x), round(y), x, y, (p[3] if len(p) > 3 else '').strip()[:60])

Q = {}
for t in texts:
    if 'WPQ1' not in t: continue
    for line in t[t.index('WPQ1'):].splitlines()[1:]:
        parts = line.strip().strip('`').split('|')
        if len(parts) < 6 or not parts[0].isdigit(): continue
        qid = int(parts[0])
        if qid <= 0 or qid > 10000000: continue
        q = Q.setdefault(qid, {'n': collections.Counter(), 'l': collections.Counter(), 'f': collections.Counter(), 's': collections.Counter(), 'e': collections.Counter(), 'sp': {}, 'ep': {}})
        name = parts[1].strip()[:80]
        if name: q['n'][name] += 1
        if parts[2].strip().isdigit(): q['l'][int(parts[2])] += 1
        if parts[3] in ('Horde', 'Alliance'): q['f'][parts[3]] += 1
        for key, field in (('s', parts[4]), ('e', parts[5])):
            sp = spot(field)
            if sp:
                k = sp[:3]
                q[key][k] += 1
                q[key + 'p'].setdefault(k, sp)

def lstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
lines = ['-- GENERATED by tools/community/import.py from players\' /wp share reports: do not edit by hand.',
         '-- Quests WoW Forever\'s published data doesn\'t have yet, with where players found their givers and hand-ins.',
         '-- RG.COMMUNITY_Q[id] = { n = name, l = level, f = "Horde"/"Alliance"/nil, s = {map, x, y, giver}, e = {...}, k = reports }',
         'local _, RG = ...', 'RG.COMMUNITY_Q = {']
kept = 0
for qid in sorted(Q):
    q = Q[qid]
    if not q['n']: continue
    bits = ['n = ' + lstr(q['n'].most_common(1)[0][0])]
    if q['l']: bits.append('l = %d' % q['l'].most_common(1)[0][0])
    if len(q['f']) == 1: bits.append('f = "%s"' % next(iter(q['f'])))
    k = 0
    for key, known in (('s', known_s), ('e', known_e)):
        if q[key] and qid not in known:
            best, cnt = q[key].most_common(1)[0]
            m, _, _, x, y, who = q[key + 'p'][best]
            bits.append('%s = { %d, %.1f, %.1f, %s }' % (key, m, x, y, lstr(who)))
            k = max(k, cnt)
    if k == 0: continue
    bits.append('k = %d' % k)
    lines.append('  [%d] = { %s },' % (qid, ', '.join(bits)))
    kept += 1
lines.append('}')
out = os.path.join(os.path.dirname(OBJ) or '.', 'CommunityQuests.lua')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('%d reports read, %d quests kept' % (sum(1 for t in texts if 'WPQ1' in t), kept), file=sys.stderr)
