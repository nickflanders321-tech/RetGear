"""Build QuestNotes.lua: per-quest tags (elite or group, escort, timed) and short "gotcha" notes ("the sacks are objects
you click, not mob drops"), from Polestar's open WoW Forever quest database (forever-db, its mechanic and step layer,
CC BY 4.0: https://github.com/fitzforge/polestar/tree/main/forever-db). The tracker shows the tag after a quest's name
and the note in its tooltip.

Usage: python3 tools/questnotes/gen.py <forever-db folder> [Waypath+ folder]
Get the folder with: git clone --depth 1 --filter=blob:none --sparse https://github.com/fitzforge/polestar /tmp/ps
                     git -C /tmp/ps sparse-checkout set forever-db
"""
import json, os, sys

DB = sys.argv[1].rstrip('/') + '/'
OUT = (sys.argv[2] if len(sys.argv) > 2 else '.').rstrip('/') + '/'
index = json.load(open(DB + 'index.json', encoding='utf-8'))

def rows(name):
    with open(DB + 'data/%s.jsonl' % name, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if line: yield json.loads(line)

TAG = {'group/elite': 'e', 'escort': 's', 'timed': 't'}
tags, notes = {}, {}
for m in rows('mechanic'):
    t = TAG.get(m.get('kind'))
    if t and (m.get('params') or {}).get('drives_route', True):
        tags.setdefault(m['quest'], set()).add(t)
for s in rows('step'):
    if s.get('action') == 'gotcha' and s.get('confidence') != 'unconfirmed':
        txt = ' '.join((s.get('text') or '').split())
        if txt and len(txt) <= 240:
            notes.setdefault(s['quest'], []).append((s.get('n') or 0, txt))

def lstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', ' ') + '"'
ids = sorted(set(tags) | set(notes))
lines = ['-- GENERATED by tools/questnotes/gen.py: do not edit by hand.',
         '-- Quest tags and notes from Polestar\'s WoW Forever quest database (forever-db %s, client %s),' % (index.get('version', '?'), index.get('clientBuild', '?')),
         '-- its mechanic and step layer, licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/),',
         '-- by the Polestar authors: https://github.com/fitzforge/polestar/tree/main/forever-db',
         '-- RG.QNOTE[quest id] = { g = "e" elite or group / "s" escort / "t" timed (any mix), n = "note" }',
         'local _, RG = ...', 'RG.QNOTE = {']
for q in ids:
    bits = []
    if q in tags: bits.append('g = "%s"' % ''.join(sorted(tags[q], key='est'.index)))
    if q in notes: bits.append('n = %s' % lstr(' '.join(t for _, t in sorted(notes[q])[:2])))
    lines.append('  [%d] = { %s },' % (q, ', '.join(bits)))
lines.append('}')
open(OUT + 'QuestNotes.lua', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('%d quests: %d tagged, %d with notes' % (len(ids), len(tags), len(notes)), file=sys.stderr)
