"""Flight masters -> FlightPaths.lua.

  python3 tools/flights/gen.py <classic.sql> <qdb dir> <npcs.tsv> <addon dir>

cMaNGOS classic.sql (creature_template NpcFlags & 8 = flight master), QuestieDB's
Forever areaId -> uiMapID table, and the NPC spawn zone/percent coordinates from npcs.tsv.
Output: RG.FLIGHTS = { {node, zone, uiMapID, x, y, faction, npcID, npcName}, ... }
"""
import re, sys, os
sql_path, qdb, npcs, addon = sys.argv[1:5]
if not qdb.endswith('/'): qdb += '/'
sql = open(sql_path, encoding='utf-8', errors='replace').read()

def columns(t):
    m = re.search(r"CREATE TABLE `%s` \((.*?)\) ENGINE" % t, sql, re.S)
    return re.findall(r"^\s*`(\w+)`", m.group(1), re.M)

def rows(t, want):
    cols = columns(t); idx = [cols.index(w) for w in want]; out = []
    for m in re.finditer(r"INSERT INTO `%s` VALUES " % t, sql):
        i, n = m.end(), len(sql)
        while i < n and sql[i] == '(':
            i += 1; row = []; cur = []; inq = False
            while True:
                c = sql[i]
                if inq:
                    if c == '\\': cur.append(sql[i + 1]); i += 2; continue
                    if c == "'":
                        if sql[i + 1] == "'": cur.append("'"); i += 2; continue
                        inq = False; i += 1; continue
                    cur.append(c); i += 1; continue
                if c == "'": inq = True; i += 1; continue
                if c == ',': row.append(''.join(cur)); cur = []; i += 1; continue
                if c == ')': row.append(''.join(cur)); i += 1; break
                cur.append(c); i += 1
            out.append([row[j] for j in idx])
            if sql[i] == ',': i += 1
            else: break
    return out

fm = {int(r[0]): (r[1], int(r[3])) for r in rows('creature_template', ['Entry', 'Name', 'SubName', 'Faction', 'NpcFlags']) if int(r[4]) & 8}
ui = {int(a): int(b) for a, b in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(qdb + 'support/Forever/Zones/areaIdToUiMapId.lua').read())}
src = open(os.path.join(os.path.dirname(__file__), '..', 'fishloot', 'gen.py'), encoding='utf-8').read()
a = src.index("AREA = {"); b = src.index("for m in re.finditer", a)
ns = {}; exec(src[a:b], ns); AREA = ns['AREA']

# the flight path's own name, by flight master NPC
