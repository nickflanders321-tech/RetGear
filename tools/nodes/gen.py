#!/usr/bin/env python3
"""Build NodeData.lua: where mining nodes and herbs can spawn, per map, from QuestieDB's Forever data.

Usage: lua5.1 dump.lua <QuestieDB>/data/Forever/foreverObjectDB.lua /tmp/veins.tsv
       python3 gen.py <QuestieDB> /tmp/veins.tsv ../../NodeData.lua
"""
import re, sys
from collections import defaultdict
qdb, tsv, out = sys.argv[1:4]
# ore type -> (bit, mining skill needed)
ORES = [("Copper Vein", 1), ("Tin Vein", 65), ("Incendicite Mineral Vein", 65), ("Silver Vein", 75), ("Lesser Bloodstone Deposit", 75),
        ("Iron Deposit", 125), ("Indurium Mineral Vein", 150), ("Gold Vein", 155), ("Mithril Deposit", 175), ("Truesilver Deposit", 230),
        ("Dark Iron Deposit", 230), ("Small Thorium Vein", 245), ("Rich Thorium Vein", 275)]
BIT = {name: i for i, (name, _) in enumerate(ORES)}
# herb -> Herbalism skill needed (WoW Forever: you also need character level = skill / 5)
HERBS = [("Peacebloom", 1), ("Silverleaf", 1), ("Earthroot", 15), ("Mageroyal", 50), ("Briarthorn", 70), ("Stranglekelp", 85),
         ("Bruiseweed", 100), ("Wild Steelbloom", 115), ("Grave Moss", 120), ("Kingsblood", 125), ("Liferoot", 150), ("Fadeleaf", 160),
         ("Goldthorn", 170), ("Khadgar's Whisker", 185), ("Wintersbite", 195), ("Firebloom", 205), ("Purple Lotus", 210),
         ("Arthas' Tears", 220), ("Sungrass", 230), ("Blindweed", 235), ("Ghost Mushroom", 245), ("Gromsblood", 250),
         ("Golden Sansam", 260), ("Dreamfoil", 270), ("Mountain Silversage", 280), ("Plaguebloom", 285), ("Icecap", 290), ("Black Lotus", 300)]
HBIT = {name: i for i, (name, _) in enumerate(HERBS)}
ui = {int(a): int(b) for a, b in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(qdb + "/support/Forever/Zones/areaIdToUiMapId.lua").read())}
DUNGEONS = set(int(x) for x in re.findall(r'\[(\d+)\] = \{"', open(qdb + "/support/Forever/Zones/dungeons.lua").read()))
spots = defaultdict(dict)  # map -> (x, y) -> mask
herbs = defaultdict(dict)
for line in open(tsv, encoding="utf-8"):
    name, z, x, y = line.rstrip("\n").split("\t")
    base = name.replace("Ooze Covered ", "")
    if base not in BIT and base not in HBIT: continue
    z = int(z)
    if z in DUNGEONS or z not in ui or ui[z] == 0: continue
    m = ui[z]
    key = (round(float(x), 1), round(float(y), 1))
    if base in BIT: spots[m][key] = spots[m].get(key, 0) | (1 << BIT[base])
    else: herbs[m][key] = herbs[m].get(key, 0) | (1 << HBIT[base])
# map names, for "where to find it" lists
MAPNAME = {}
for m_ in re.finditer(r'\[(\d+)\]\s*=\s*(\d+),\s*--\s*([^\n>]+?)\s*$', open(qdb + "/support/Forever/Zones/areaIdToUiMapId.lua").read(), re.M):
    MAPNAME.setdefault(int(m_.group(2)), m_.group(3).strip())
# Alliance home zones: listed as places to gather only if nothing else has it
ALLIANCE = {"Elwynn Forest", "Dun Morogh", "Teldrassil", "Westfall", "Loch Modan", "Darkshore", "Redridge Mountains",
            "Stormwind City", "Ironforge", "Darnassus", "Azuremyst Isle", "Bloodmyst Isle"}
def top_zones(table, types):
    out = {}
    for i, (name, _) in enumerate(types):
        counts = []
        for m, pts in table.items():
            c = sum(1 for mask in pts.values() if mask & (1 << i))
            if c and m in MAPNAME and MAPNAME[m] not in ALLIANCE: counts.append((c, MAPNAME[m]))
        counts.sort(reverse=True)
        out[name] = [z for c, z in counts[:4] if c >= 5]
    return out
total = sum(len(v) for v in spots.values())
print("maps %d, spots %d, herb spots %d" % (len(spots), total, sum(len(v) for v in herbs.values())), file=sys.stderr)
with open(out, "w", encoding="utf-8") as f:
    f.write("-- GENERATED by tools/nodes/gen.py: do not edit by hand.\n")
    f.write("-- Where mining nodes (and herbs, below) can spawn in WoW Forever (QuestieDB Forever object data), per map.\n")
    f.write("-- Each spot is \"x,y,mask\" (map percent; mask = ore types that spawn there, see RG.NODE_ORES).\n")
    f.write("local _, RG = ...\n")
    f.write("RG.NODE_ORES = {\n")
    for name, skill in ORES: f.write("  { %s, %d },\n" % ('"' + name + '"', skill))
    f.write("}\n")
    f.write("RG.NODE_SPOTS = {\n")
    for m in sorted(spots):
        parts = ["%g,%g,%d" % (x, y, mask) for (x, y), mask in sorted(spots[m].items())]
        f.write("  [%d] = \"%s\",\n" % (m, ";".join(parts)))
    f.write("}\n")
    def zones_block(var, table, types):
        f.write("-- Best zones for each, by number of spawn points\n%s = {\n" % var)
        for name, zs in top_zones(table, types).items():
            if zs: f.write("  [%s] = %s,\n" % ('"' + name.replace("'", "\\'") + '"', '"' + ", ".join(zs).replace('"', '') + '"'))
        f.write("}\n")
    zones_block("RG.ORE_ZONES", spots, ORES)
    f.write("-- Herbs: same format, mask = herb types (see RG.HERB_TYPES).\n")
    f.write("RG.HERB_TYPES = {\n")
    for name, skill in HERBS: f.write("  { %s, %d },\n" % ('"' + name.replace("'", "\\'") + '"', skill))
    f.write("}\n")
    f.write("RG.HERB_SPOTS = {\n")
    for m in sorted(herbs):
        parts = ["%g,%g,%d" % (x, y, mask) for (x, y), mask in sorted(herbs[m].items())]
        f.write("  [%d] = \"%s\",\n" % (m, ";".join(parts)))
    f.write("}\n")
    zones_block("RG.HERB_ZONES", herbs, HERBS)
