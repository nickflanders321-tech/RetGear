#!/usr/bin/env python3
"""Build NodeData.lua: where mining nodes can spawn, per map, from QuestieDB's Forever data.

Usage: lua5.1 dump.lua <QuestieDB>/data/Forever/foreverObjectDB.lua /tmp/veins.tsv
       python3 gen.py <QuestieDB> /tmp/veins.tsv ../../NodeData.lua
"""
import re, sys
from collections import defaultdict
qdb, tsv, out = sys.argv[1:4]
# ore type -> (bit, mining skill needed)
ORES = [("Copper Vein", 1), ("Tin Vein", 65), ("Incendicite Mineral Vein", 65), ("Silver Vein", 75), ("Lesser Bloodstone Deposit", 75),
        ("Iron Deposit", 125), ("Indurium Mineral Vein", 150), ("Gold Vein", 155), ("Mithril Deposit", 175), ("Truesilver Deposit", 230),
        ("Dark Iron Deposit", 230), ("Small Thorium Vein", 245), ("Rich Thorium Vein", 275)]
BIT = {name: i for i, (name, _) in enumerate(ORES)}
ui = {int(a): int(b) for a, b in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(qdb + "/support/Forever/Zones/areaIdToUiMapId.lua").read())}
DUNGEONS = set(int(x) for x in re.findall(r'\[(\d+)\] = \{"', open(qdb + "/support/Forever/Zones/dungeons.lua").read()))
spots = defaultdict(dict)  # map -> (x, y) -> mask
for line in open(tsv, encoding="utf-8"):
    name, z, x, y = line.rstrip("\n").split("\t")
    base = name.replace("Ooze Covered ", "")
    if base not in BIT: continue
    z = int(z)
    if z in DUNGEONS or z not in ui or ui[z] == 0: continue
    m = ui[z]
    key = (round(float(x), 1), round(float(y), 1))
    spots[m][key] = spots[m].get(key, 0) | (1 << BIT[base])
total = sum(len(v) for v in spots.values())
print("maps %d, spots %d" % (len(spots), total), file=sys.stderr)
with open(out, "w", encoding="utf-8") as f:
    f.write("-- GENERATED by tools/nodes/gen.py: do not edit by hand.\n")
    f.write("-- Where mining nodes can spawn in WoW Forever (QuestieDB Forever object data), per map.\n")
    f.write("-- Each spot is \"x,y,mask\" (map percent; mask = ore types that spawn there, see RG.NODE_ORES).\n")
    f.write("local _, RG = ...\n")
    f.write("RG.NODE_ORES = {\n")
    for name, skill in ORES: f.write("  { %s, %d },\n" % ('"' + name + '"', skill))
    f.write("}\n")
    f.write("RG.NODE_SPOTS = {\n")
    for m in sorted(spots):
        parts = ["%g,%g,%d" % (x, y, mask) for (x, y), mask in sorted(spots[m].items())]
        f.write("  [%d] = \"%s\",\n" % (m, ";".join(parts)))
    f.write("}\n")
