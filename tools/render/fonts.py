"""Font metrics for the harness: every character's advance width, from the fonts the add-on uses (the game's own,
read from the install, and Media/Fonts). Written to tools/harness/.cache/fontmetrics.lua, keyed by the path as the
add-on names it (upper case, backslashes). Also copies the game's fonts into .cache/game/fonts for the renderer.

    python3 tools/render/fonts.py
"""
import os, struct, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CACHE = os.path.join(HERE, "..", "harness", ".cache")
GAME_FONTS = ["Fonts\\FRIZQT__.TTF", "Fonts\\ARIALN.TTF", "Fonts\\MORPHEUS.TTF", "Fonts\\skurri.ttf", "Fonts\\FRIZQT___CYR.TTF"]


def ttf_metrics(data):
    """{codepoint: advance / unitsPerEm}, and the ascent/descent, from a TrueType font."""
    num = struct.unpack_from(">H", data, 4)[0]
    tables = {}
    for i in range(num):
        tag, _, off, ln = struct.unpack_from(">4sIII", data, 12 + 16 * i)
        tables[tag.decode("latin-1")] = (off, ln)
    upem = struct.unpack_from(">H", data, tables["head"][0] + 18)[0]
    hh = tables["hhea"][0]
    asc, desc = struct.unpack_from(">hh", data, hh + 4)
    nhm = struct.unpack_from(">H", data, hh + 34)[0]
    hm = tables["hmtx"][0]
    adv = [struct.unpack_from(">H", data, hm + 4 * i)[0] for i in range(nhm)]
    cm = tables["cmap"][0]
    n = struct.unpack_from(">H", data, cm + 2)[0]
    best = None
    for i in range(n):
        pid, eid, off = struct.unpack_from(">HHI", data, cm + 4 + 8 * i)
        fmt = struct.unpack_from(">H", data, cm + off)[0]
        if fmt == 12 and (best is None or best[0] != 12):
            best = (12, cm + off)
        elif fmt == 4 and best is None and pid in (0, 3):
            best = (4, cm + off)
    cmap = {}
    if best and best[0] == 4:
        o = best[1]
        segx2 = struct.unpack_from(">H", data, o + 6)[0]
        seg = segx2 // 2
        ends = struct.unpack_from(">%dH" % seg, data, o + 14)
        starts = struct.unpack_from(">%dH" % seg, data, o + 16 + segx2)
        deltas = struct.unpack_from(">%dh" % seg, data, o + 16 + 2 * segx2)
        ro = o + 16 + 3 * segx2
        ranges = struct.unpack_from(">%dH" % seg, data, ro)
        for s in range(seg):
            for c in range(starts[s], ends[s] + 1):
                if c == 0xFFFF:
                    continue
                if ranges[s] == 0:
                    g = (c + deltas[s]) & 0xFFFF
                else:
                    a = ro + 2 * s + ranges[s] + 2 * (c - starts[s])
                    g = struct.unpack_from(">H", data, a)[0]
                    if g:
                        g = (g + deltas[s]) & 0xFFFF
                if g:
                    cmap[c] = g
    elif best:
        o = best[1]
        ng = struct.unpack_from(">I", data, o + 12)[0]
        for i in range(ng):
            s, e, g = struct.unpack_from(">III", data, o + 16 + 12 * i)
            for c in range(s, min(e, 0x2FFFF) + 1):
                cmap[c] = g + (c - s)
    out = {}
    for c, g in cmap.items():
        if c > 0x2FFF and c < 0xFF00:
            continue   # (CJK and the like: not in the add-on's text)
        a = adv[g] if g < len(adv) else adv[-1]
        out[c] = a / upem
    return out, asc / upem, -desc / upem


def main():
    sys.path.insert(0, HERE)
    fonts = {}
    try:
        from casc import Casc
        c = Casc()
        os.makedirs(os.path.join(CACHE, "game", "fonts"), exist_ok=True)
        for p in GAME_FONTS:
            d = c.read(p)
            if d:
                fonts[p.upper()] = d
                open(os.path.join(CACHE, "game", "fonts", os.path.basename(p).upper()), "wb").write(d)
    except Exception as e:  # no install: only the add-on's own fonts
        print("(no game fonts: %s)" % e)
    mf = os.path.join(ROOT, "Media", "Fonts")
    for n in sorted(os.listdir(mf)):
        if n.lower().endswith((".ttf", ".otf")):
            fonts[("Interface\\AddOns\\Waypath\\Media\\Fonts\\" + n).upper()] = open(os.path.join(mf, n), "rb").read()
    lines = ["-- generated by tools/render/fonts.py: advance widths per size-1 font, ascent, descent", "local F = {}"]
    for key, data in sorted(fonts.items()):
        try:
            adv, asc, desc = ttf_metrics(data)
        except Exception as e:
            print("can't read %s: %s" % (key, e))
            continue
        avg = sum(adv.get(c, 0.5) for c in range(97, 123)) / 26
        parts = ["[%d]=%.4f" % (c, a) for c, a in sorted(adv.items()) if c < 0x3000]
        lines.append('F[%q] = { def = %.4f, asc = %.4f, desc = %.4f, adv = { %s } }'.replace("%q", '"%s"') % (
            key.replace("\\", "\\\\"), avg, asc, desc, ", ".join(parts)))
        print("%-60s %5d glyphs" % (key, len(adv)))
    lines.append("return F")
    os.makedirs(CACHE, exist_ok=True)
    open(os.path.join(CACHE, "fontmetrics.lua"), "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
