"""Camera distances for the current step's model (StepView.lua) and other small model frames: ModelCams.lua.

A creature model with no camera of its own for the whole body (the model file's "character info" camera, type 1;
409 of the client's ~1000 creature models) is framed too close by the game: the step card showed Hyacinth's legs and
nothing else. For each such model this finds the camera distance (SetCamDistanceScale) at which the whole creature
fits the step card's picture, keyed by the model's file ID (what the model frame's GetModelFileID answers once it has
loaded, for any NPC, WoW Forever's new ones too).

    python3 tools/render/stepcam.py [ModelCams.lua]      # from the repo root, in WSL

Needs the local install (casc.py) and the model tables (python3 tools/render/modeldata.py). Local only: the output is
committed, and rebuilt by hand when the client's models change (not by tools/watch/regenerate.sh).
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import model
from render import silhouette

W, H = 80, 92            # StepView.lua's MODEL_W, MODEL_H
FACING = 0.45            # as the step card turns it
ROOM = 0.03              # clear of each edge


def framing(disp, cam):
    it = {"disp": disp, "zoom": 0, "cam": cam, "facing": FACING, "pos": [0, 0, 0], "scale": 1, "r": [0, 0, W, H], "log": []}
    img = model.render_item(it, W, H)
    return silhouette(img[..., 3]) if img is not None else None


def fits(st):
    b = st and st["box"]
    return bool(b) and b[0] >= ROOM and b[1] >= ROOM and b[2] <= 1 - ROOM and b[3] <= 1 - ROOM


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "ModelCams.lua")
    disp = model.data()["display"]
    by_file = {}
    for did, v in sorted(disp.items()):
        if v.get("file") and v["file"] not in by_file:
            by_file[v["file"]] = did
    fixes, skipped = {}, 0
    for i, (fid, did) in enumerate(sorted(by_file.items())):
        try:
            m = model.load_model(fid)
        except Exception:
            skipped += 1
            continue
        if any(c["type"] == 1 for c in m.cameras):
            continue
        try:
            if fits(framing(did, 1.0)):
                continue
            lo, hi = 1.0, 6.0
            if not fits(framing(did, hi)):
                skipped += 1
                continue
            for _ in range(8):               # binary search: to within about 1%
                mid = (lo + hi) / 2
                if fits(framing(did, mid)):
                    hi = mid
                else:
                    lo = mid
            fixes[fid] = round(hi * 1.02, 2)
        except Exception as e:
            print("-- %s: %s" % (fid, e), file=sys.stderr)
            skipped += 1
        if i % 50 == 0:
            print("%d/%d models, %d fixes" % (i, len(by_file), len(fixes)), file=sys.stderr)
    lines = [
        "-- GENERATED by tools/render/stepcam.py from the client's creature models: do not edit.",
        "-- Camera distance (SetCamDistanceScale) for a creature model with no whole-body camera of its own, keyed by",
        "-- its model file ID, so the whole creature fits a small model frame (the current step's picture, StepView.lua).",
        "local _, RG = ...",
        "RG.MODEL_CAM = {",
    ]
    row = []
    for fid in sorted(fixes):
        row.append("[%d]=%s" % (fid, fixes[fid]))
        if len(row) == 8:
            lines.append("  " + ", ".join(row) + ","); row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    lines.append("}")
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("%d models need the camera further back; %d skipped. Wrote %s" % (len(fixes), skipped, out_path))


if __name__ == "__main__":
    main()
