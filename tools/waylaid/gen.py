items_tsv, wago = sys.argv[1], sys.argv[2]
byname, crates = {}, {}
for line in open(items_tsv, encoding='utf-8'):
    p = line.rstrip("\n").split("\t")
    if len(p) < 2: continue
    iid, name = int(p[0]), p[1]
    if name.startswith("Waylaid Crate: "): crates[name[len("Waylaid Crate: "):]] = iid
    elif name not in byname or iid < byname[name]: byname[name] = iid   # (the original item, not a later copy)

def rows(n):
    with gzip.open(os.path.join(wago, n + '.csv.gz'), 'rt', encoding='utf-8') as f:
        r = csv.reader(f); h = next(r)
        for x in r: yield dict(zip(h, x))
effect_of = {x['ItemID']: x['ItemEffectID'] for x in rows('ItemXItemEffect')}
spell_of = {x['ID']: x['SpellID'] for x in rows('ItemEffect')}
counts = {}
for x in rows('SpellEffect'):
    if x['Effect'] == '3' and x.get('EffectBasePointsF') not in (None, '', '0'):
        counts.setdefault(x['SpellID'], []).append(int(float(x['EffectBasePointsF'])))

out = ["-- GENERATED by tools/waylaid/gen.py: do not edit by hand.",
       "-- Waylaid Crates: [crate item id] = { name, { { material id, count, name }, ... } }; any one bundle fills it.",
       "local _, RG = ...", "RG.WAYLAID = {"]
bad = 0
for kind, bundles in sorted(BUNDLES.items(), key=lambda kv: crates.get(kv[0], 0)):
    cid = crates.get(kind)
    if not cid: print("no crate item for", kind, file=sys.stderr); bad += 1; continue
    sp = spell_of.get(effect_of.get(str(cid), ''), '')
    game = sorted(counts.get(sp, []))
    if game and game != sorted(c for c, _ in bundles):
        print("counts differ for %s: game %s, list %s" % (kind, game, sorted(c for c, _ in bundles)), file=sys.stderr); bad += 1
    parts = []
    for c, n in bundles:
        mid = byname.get(n)
        if not mid: print("no item for", n, file=sys.stderr); bad += 1; continue
        parts.append('{ %d, %d, "%s" }' % (mid, c, n.replace('"', '\\"')))
    out.append('  [%d] = { "%s", { %s } },' % (cid, kind, ", ".join(parts)))
out.append("}")
print("\n".join(out))
sys.exit(1 if bad else 0)
