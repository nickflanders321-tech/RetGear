#!/usr/bin/env python3
"""Waylaid Crates -> Waylaid.lua: what each crate takes (any one bundle fills it).

The bundles (material and count) are WoW Forever's, as listed by players (foreverdiff.com's crate list); the counts are
checked against the game's own data: each crate's "Stock Crate" spell carries one effect per bundle with its count.
Item ids come from the game's item names (items.tsv from the regen pipeline).
Usage: python3 tools/waylaid/gen.py <items.tsv> <wago dir> > Waylaid.lua
"""
