-- Which Arena cards an update changes, for the two-week full-value refund. Usage:
--   git show <old release>:Battle.lua > /tmp/old/Battle.lua   (and ArcadeBalance.lua, ArcadeCards.lua; ArcadeClasses.lua if it existed)
--   texlua tools/balance/changes.lua /tmp/old <patch id> "<one-line note>"
-- Compares every collectible card as it plays (cost, stats, text) under the old and the new rules and writes
-- ArcadeChanges.lua: RG.ARCADE_PATCH = { id, note, changed = { [name] = true } }.
local dir = arg[0]:match("^(.*)/tools/balance/") or "."
local old, id, note = arg[1], arg[2], arg[3] or "some cards changed"
assert(old and id, "usage: changes.lua OLD_DIR PATCH_ID [NOTE]")
local function load(base)
  local RG = {}
  for _, f in ipairs({ "ArcadeCards.lua", "ArcadeMythic.lua", "ArcadeClasses.lua", "ArcadeBalance.lua", "Battle.lua" }) do
    local chunk = loadfile(base .. "/" .. f)
    if chunk then chunk("Waypath", RG) elseif f ~= "ArcadeClasses.lua" and f ~= "ArcadeMythic.lua" then error("missing " .. base .. "/" .. f) end
  end
  local B, out = RG.Battle, {}
  for i, c in ipairs(RG.ARCADE_DATA) do
    local d = B.derive({ id = i, kind = c[1], name = c[2], tier = c[3], ref = c[4], text = c[5] })
    out[c[2]] = table.concat({ d.type, d.cost, d.atk or "", d.hp or d.dur or "", d.text or "", d.hclass or "" }, "|")
  end
  return out
end
local a, b = load(old), load(dir)
local names = {}
for k, v in pairs(b) do if a[k] and a[k] ~= v then names[#names + 1] = k end end
table.sort(names)
local f = assert(io.open(dir .. "/ArcadeChanges.lua", "w"))
f:write("-- GENERATED by tools/balance/changes.lua: do not edit by hand.\n")
f:write("-- The cards the latest Arena update changed: for two weeks they sell back for their full crafting value.\n")
f:write("local _, RG = ...\n")
f:write(string.format("RG.ARCADE_PATCH = { id = %q, note = %q, changed = {\n", id, note))
for _, k in ipairs(names) do f:write(string.format("  [%q] = true,\n", k)) end
f:write("} }\n")
f:close()
print(#names .. " cards changed; wrote ArcadeChanges.lua")
