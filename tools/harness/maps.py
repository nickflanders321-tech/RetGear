"""The game's maps for the harness's simulated world: each map's name, parent and type (UiMap), and where it sits in
the world (UiMapAssignment: the world coordinates its corners cover, and its continent), from the client's own DB2
tables as wago.tools exports them. With these the world names maps as the game does, the add-on can walk up from a
map to its zone and continent, and distances between zones are real.

Usage: python3 maps.py <UiMap.csv> <UiMapAssignment.csv> <out.lua>   (tools/harness/maps.sh downloads the tables)
"""
import csv, sys

maps, assign = {}, {}
for r in csv.DictReader(open(sys.argv[1], encoding='utf-8')):
    maps[int(r['ID'])] = (r['Name_lang'], int(r['ParentUiMapID'] or 0), int(r['Type'] or 0))
for r in csv.DictReader(open(sys.argv[2], encoding='utf-8')):
    m = int(r['UiMapID'])
    if int(r['OrderIndex'] or 0) != 0 or m in assign: continue
    f = lambda k: float(r[k])
    assign[m] = (int(r['MapID']), f('UiMin_0'), f('UiMin_1'), f('UiMax_0'), f('UiMax_1'), f('Region_0'), f('Region_1'), f('Region_3'), f('Region_4'))

def lstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
with open(sys.argv[3], 'w', encoding='utf-8') as out:
    out.write('-- GENERATED by tools/harness/maps.py from the client\'s UiMap and UiMapAssignment tables (wago.tools).\n')
    out.write('-- maps[id] = { name, parent, type }; at[id] = { continent, uMin, vMin, uMax, vMax, minX, minY, maxX, maxY }\n')
    out.write('return { maps = {\n')
    for m, (n, p, t) in sorted(maps.items()): out.write('  [%d] = { %s, %d, %d },\n' % (m, lstr(n), p, t))
    out.write('}, at = {\n')
    for m, a in sorted(assign.items()): out.write('  [%d] = { %d, %g, %g, %g, %g, %.3f, %.3f, %.3f, %.3f },\n' % ((m,) + a))
    out.write('} }\n')
print('%d maps, %d with world coordinates' % (len(maps), len(assign)), file=sys.stderr)
