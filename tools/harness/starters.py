"""Where each quest that starts from an object or an item begins, for the harness's simulated world (run.lua --play).

The add-on's quest data (Objectives.lua) only knows quests handed out by an NPC. This reads QuestieDB's merged Forever
data and writes, for every quest started by an object (a crate, a corpse, a letter) or by an item that drops from
mobs, where that is: the object's spawns, or the spawns of the mobs that drop the item.

Usage: python3 starters.py <QuestieDB checkout> <forever.json from tools/objectives/dump.lua> <out.lua>
(tools/harness/starters.sh does the downloads and writes tools/harness/.cache/starters.lua.)
"""
import json, re, sys

QDB, JSON_IN, OUT = sys.argv[1].rstrip('/') + '/', sys.argv[2], sys.argv[3]
D = json.load(open(JSON_IN, encoding='utf-8'))
ui = {int(a): int(b) for a, b in re.findall(r'\[(\d+)\]\s*=\s*(\d+)', open(QDB + 'support/Forever/Zones/areaIdToUiMapId.lua').read())}

def at(a, i):
    if a is None: return None
    if isinstance(a, dict): return a.get(str(i))
    return a[i - 1] if 0 < i <= len(a) else None

def spots(spawns, limit):
    """[(uiMapID, x, y)] from a {zone: [[x, y], ...]} spawn table (up to limit in each zone)."""
    out = []
    if not isinstance(spawns, dict): return out
    for z, pts in spawns.items():
        m = ui.get(int(z)) if str(z).lstrip('-').isdigit() else None
        if not m: continue
        for p in (pts or [])[:limit]:
            if p and p[0] is not None and p[0] >= 0: out.append((m, round(p[0], 1), round(p[1], 1)))
    return out

rows = []
for qid, q in D['quests'].items():
    st = at(q, 2)
    objs, items = at(st, 2) or [], at(st, 3) or []
    if not objs and not items: continue
    kind, item, where = None, None, []
    for o in objs:
        e = D['objects'].get(str(o))
        if e: where += spots(at(e, 2), 40)       # every spawn: the add-on may send you to any of them
    if objs: kind = 'o'
    for it in items:
        e = D['items'].get(str(it))
        if not e: continue
        item, kind = int(it), kind or 'i'
        for n in (at(e, 2) or [])[:4]:          # the mobs that drop it
            ne = D['npcs'].get(str(n))
            if ne: where += spots(at(ne, 2), 40)
        for o in (at(e, 3) or [])[:4]:          # or the objects it's found in
            oe = D['objects'].get(str(o))
            if oe: where += spots(at(oe, 2), 40)
    rows.append((int(qid), kind, item, where[:120]))

rows.sort()
with open(OUT, 'w', encoding='utf-8') as f:
    f.write('-- GENERATED by tools/harness/starters.py from QuestieDB\'s merged Forever data: where quests that start from an\n')
    f.write('-- object (k = "o") or a dropped item (k = "i") begin. [questID] = { k, item = itemID, s = { {uiMapID, x, y}, ... } }\n')
    f.write('return {\n')
    for qid, kind, item, where in rows:
        s = ', '.join('{ %d, %.1f, %.1f }' % w for w in where)
        f.write('  [%d] = { k = "%s"%s, s = { %s } },\n' % (qid, kind, (', item = %d' % item) if item else '', s))
    f.write('}\n')
print('%d quests start from an object or item; %d with a known place' % (len(rows), sum(1 for r in rows if r[3])), file=sys.stderr)
